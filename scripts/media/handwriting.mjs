function word(text, x, y, size) {
  const paths = [];
  let cursor = x;

  for (const letter of text) {
    if (letter === " ") {
      cursor += size * 0.55;
      continue;
    }

    const glyph = glyphs[letter];

    if (!glyph) throw new Error(`No demo glyph for ${letter}`);

    paths.push(
      ...glyph.map((path) =>
        path.map(([u, v]) => [
          cursor + (u + 0.08 * (1 - v)) * size * 0.7,
          y + v * size,
        ]),
      ),
    );

    cursor += size * 0.96;
  }

  return paths;
}

